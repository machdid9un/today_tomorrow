/** 회차마다 고정된 뼈대 하나 (같은 회차에서 다시 불러도 같은 결과) */
export function plotPatternFor(key: string): PlotPattern {
  let h = 29;
  for (const ch of key) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return PLOT_PATTERNS[h % PLOT_PATTERNS.length];
}
