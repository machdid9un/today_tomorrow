interface CompiledRule {
  re: RegExp;
  correct: string;
}

function compile(): CompiledRule[] {
  return CORRECTIONS.filter(([variants]) => variants.length > 0).map(([variants, correct]) => ({
    re: new RegExp(`(^|\\s)(${variants.map(escapeRegExp).join("|")})(?=\\s|$)`, "gu"),
    correct,
  }));
}

let compiled: CompiledRule[] | null = null;
function rules(): CompiledRule[] {
  return compiled ?? (compiled = compile());
}

/**
 * STT 텍스트를 보정 사전으로 치환한다.
 * @param text STT 원문(또는 isLikelySttHallucination을 거친 뒤의 텍스트)
 * @param protect 치환에서 보호할 낱말(아이 이름, 아이가 이 별에서 지은 이름 등). 어절 전체가 정확히
 *   일치할 때만 보호한다.
 */
export function correctSttText(text: string, protect: string[] = []): string {
  if (!text) return text;

  // 보호 낱말을 먼저 플레이스홀더로 바꿔 둔다(긴 것부터 — 겹치는 이름이 있을 때 안전하게).
  const protectedNames = [...new Set(protect.map((p) => p.trim()).filter(Boolean))].sort(
    (a, b) => b.length - a.length
  );
  let out = text;
  const placeholders: Array<{ token: string; name: string }> = [];
  protectedNames.forEach((name, i) => {
    const token = `\u0000${i}\u0000`;
    const re = new RegExp(`(^|\\s)(${escapeRegExp(name)})(?=\\s|$)`, "gu");
    if (re.test(out)) {
      out = out.replace(re, `$1${token}`);
      placeholders.push({ token, name });
    }
  });

  for (const { re, correct } of rules()) {
    out = out.replace(re, `$1${correct}`);
  }

  for (const { token, name } of placeholders) {
    out = out.split(token).join(name);
  }
  return out;
}
